// Topic: Operators
// Description: Perform +, -, *, /, ~/ (integer division), and % on two integers. Print each result.
// ============================================================================

void main() {
  print('--- Question 05: Arithmetic Operations in Dart ---');

  int a = 25;
  int b = 4;

  print('Given operands: a = $a, b = $b\n');
  print('Addition (a + b)            : ${a + b}');
  print('Subtraction (a - b)         : ${a - b}');
  print('Multiplication (a * b)      : ${a * b}');
  print('Standard Division (a / b)   : ${a / b}');
  print('Integer Division (a ~/ b)   : ${a ~/ b}');
  print('Modulus / Remainder (a % b) : ${a % b}');
}
